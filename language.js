const requestedLanguage = new URLSearchParams(location.search).get("lang");
const language = requestedLanguage === "es" || requestedLanguage === "ko" ? requestedLanguage : "en";
const messages = translations[language];
document.documentElement.lang = language;

if (messages) {
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = messages[element.dataset.i18n];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", messages[element.dataset.i18nAria]);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.setAttribute("alt", messages[element.dataset.i18nAlt]);
  });
  document.querySelector('meta[name="description"]').content = messages.metaDescription;
  document.querySelector('meta[property="og:description"]').content = messages.metaTagline;
  document.querySelector('meta[name="twitter:description"]').content = messages.metaTagline;
  document.querySelector('meta[property="og:image:alt"]').content = messages.previewAlt;
  document.querySelector('meta[name="twitter:image:alt"]').content = messages.previewAlt;
}

document.querySelectorAll("[data-language]").forEach((link) => {
  const url = new URL(location.href);
  url.searchParams.set("lang", link.dataset.language);
  link.href = url.href;
  if (link.dataset.language === language) link.setAttribute("aria-current", "page");
});
